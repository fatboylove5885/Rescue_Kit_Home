class PublishingBlocked(Exception):pass

def ensure(condition,message):
    if not condition:raise PublishingBlocked(message)

def font(size,serif=False):
    candidates=(["/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf", "/usr/share/fonts/truetype/liberation2/LiberationSerif-Bold.ttf"] if serif else ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf"])
    return ImageFont.truetype(next(x for x in candidates if Path(x).exists()),size)

def lines_fit(draw,s,max_width,max_lines=3,initial=92):
    for size in range(initial,39,-2):
        f=font(size,serif=True);lines=[];row=''
        for word in s.split():
            guess=(row+' '+word).strip()
            if draw.textbbox((0,0),guess,font=f)[2]<=max_width:row=guess
            else:
                if row:lines.append(row)
                row=word
        if row:lines.append(row)
        if len(lines)<=max_lines:return f,lines
    raise PublishingBlocked('Headline does not fit mobile-friendly layout: '+s)

def _title_lines(headline):
    """Large mobile-first two-line editorial typography, not tiny generic cards."""
    words=str(headline).upper().split()
    if not words:return ["EASY", "DINNERS"]
    if len(words)==1:return ["EASY",words[0]]
    if len(words)==2:return words
    if words[-1] in ("DINNERS","RECIPES","IDEAS","MEALS","PLAN"):
        return [" ".join(words[:-1]),words[-1]]
    # Choose the most balanced natural pair, avoiding tiny final lines.
    choices=[(" ".join(words[:n])," ".join(words[n:])) for n in range(1,len(words))]
    return list(min(choices,key=lambda x:max(len(x[0]),len(x[1]))+0.14*abs(len(x[0])-len(x[1]))))

def _fit_heading(draw,s,max_px,start=104):
    for size in range(start,49,-2):
        ff=font(size,serif=True)
        if draw.textbbox((0,0),s,font=ff)[2] <=max_px:return ff
    raise PublishingBlocked('Creative headline cannot fit 1000px wide card: '+s)

def compose(photo:Image.Image,concept:dict,index:int)->Image.Image:
    """Photo-led editorial concept inspired by Oct26 + Oct27 approved Medium lab.
    Original meal imagery spans nearly entire card; only small header/CTA
    overlays. Sourced visual reference notes guide the PHOTO prompt upstream.
    """
    if VARIANT:
        return compose_redo(photo,concept,index)
    out=ImageOps.fit(photo.convert('RGB'),(1000,1500),method=Image.Resampling.LANCZOS)
    if concept.get('content_type')=='free_pdf':
        # Preview exact real PDF pixels, not invented AI text or a fake printable.
        # The promotional companion page is at the END; the thumbnail is page 1.
        import fitz
        pdfpath=ROOT/concept['pdf_slug']
        with fitz.open(str(pdfpath)) as doc:
            pix=doc[0].get_pixmap(matrix=fitz.Matrix(1.55,1.55),alpha=False)
            preview=Image.frombytes('RGB',(pix.width,pix.height),pix.samples)
        preview.thumbnail((440,770),Image.Resampling.LANCZOS)
        # Drop-shadow behind the genuine preview, which remains readable on mobile.
        x=1000-preview.width-65;y=460
        d0=ImageDraw.Draw(out,'RGBA')
        d0.rounded_rectangle((x-16,y-17,x+preview.width+17,y+preview.height+21),
                             radius=24,fill=(20,32,24,150))
        out.paste(preview,(x,y))
