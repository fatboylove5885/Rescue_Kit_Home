#!/usr/bin/env python3
"""Research-gated, original FIRST-PARTY image generation for What's For Eats.

Every run requires a dated, user-researched manifest and an OpenAI API key.
Nine new original food photographs are generated by OpenAI's image API. Existing
website photos are never reused as the images for these pins. If inputs are
missing/invalid, the feed is not modified. Companion daily research happens
upstream in ChatGPT; this script never invents reference evidence.
"""
from __future__ import annotations
import base64, datetime as dt, email.utils, hashlib, io, json, os, re, sys, urllib.request, urllib.error
from pathlib import Path
from urllib.parse import urlparse
from zoneinfo import ZoneInfo
import xml.etree.ElementTree as ET
from PIL import Image, ImageOps, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parent.parent
BASE="https://whatsforeats.online/"
MEDIA_NS="http://search.yahoo.com/mrss/"
ET.register_namespace('media',MEDIA_NS)
TODAY=dt.datetime.now(ZoneInfo('America/Detroit')).date()
if os.environ.get('PIN_DATE'): TODAY=dt.date.fromisoformat(os.environ['PIN_DATE'])
DATE=TODAY.isoformat()
RESEARCH=ROOT/'pinterest-research'/DATE/'manifest.json'
DEST=ROOT/'pinterest-daily-pins'/DATE
RSS=ROOT/'pinterest-rss.xml'
LEDGER=ROOT/'pinterest-publishing-ledger'/f'{DATE}.json'
OPENAI_IMAGE_MODEL=os.getenv('OPENAI_IMAGE_MODEL','gpt-image-2')
CREAM=(250,247,237);GREEN=(22,66,45);RUST=(191,58,25);DARK=(43,29,25)

class PublishingBlocked(Exception):pass

def ensure(condition,message):
    if not condition:raise PublishingBlocked(message)

def font(size,serif=False):
    candidates=(["/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf", "/usr/share/fonts/truetype/liberation2/LiberationSerif-Bold.ttf"] if serif else ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf"])
    return ImageFont.truetype(next(x for x in candidates if Path(x).exists()),size)

def lines_fit(draw,s,max_width,max_lines=3,initial=92):
    for size in range(initial,39,-2):
        f=font(size,serif=True);lines=[];row=''
        for word in s.split():
            guess=(row+' '+word).strip()
            if draw.textbbox((0,0),guess,font=f)[2]<=max_width:row=guess
            else:
                if row:lines.append(row)
                row=word
        if row:lines.append(row)
        if len(lines)<=max_lines:return f,lines
    raise PublishingBlocked('Headline does not fit mobile-friendly layout: '+s)

def compose(photo:Image.Image,concept:dict,index:int)->Image.Image:
    # Three related food-blog layouts; photographic content is wholly original.
    style=concept.get('layout','hero')
    out=Image.new('RGB',(1000,1500),CREAM); d=ImageDraw.Draw(out)
    p=ImageOps.fit(photo.convert('RGB'),(1000,960),method=Image.Resampling.LANCZOS)
    if style=='hero':
        out.paste(p,(0,350)); top=(0,350)
    elif style=='photo_first':
        out.paste(p,(0,0)); d.rectangle((0,950,1000,1320),fill=CREAM);top=(950,1320)
    elif style=='editorial':
        out.paste(p,(0,350));d.rectangle((0,350,1000,425),fill=CREAM);top=(0,350)
    else:raise PublishingBlocked('Unsupported design layout: '+str(style))
    d=ImageDraw.Draw(out)
    brand='WHAT\'S FOR EATS';bf=font(24)
    if top[0]==0:
        d.text((500,42),brand,font=bf,fill=DARK,anchor='mm')
        f,rows=lines_fit(d,concept['headline'],908,max_lines=2,initial=80)
        step=f.size*1.15;y=112
        for k,txt in enumerate(rows):d.text((500,int(y+k*step)),txt,font=f,fill=RUST if k==len(rows)-1 and len(rows)>1 else GREEN,anchor='mt')
        subtitle=concept.get('subheadline','Easy meals for busy days')
        d.text((500,326),subtitle[:62],font=font(24,serif=True),fill=DARK,anchor='mm')
    else:
        d.text((500,975),brand,font=bf,fill=DARK,anchor='mm')
        f,rows=lines_fit(d,concept['headline'],908,max_lines=3,initial=82)
        step=f.size*1.12; y=1018
        for k,txt in enumerate(rows):d.text((500,int(y+k*step)),txt,font=f,fill=RUST if k==len(rows)-1 else GREEN,anchor='mt')
    d.rectangle((0,1320,1000,1500),fill=CREAM)
    d.rounded_rectangle((140,1340,860,1433),radius=47,fill=RUST)
    d.text((500,1387),'SEE THE EASY RECIPES',font=font(31),fill=(255,255,255),anchor='mm')
    d.text((500,1470),'whatsforeats.online',font=font(24),fill=DARK,anchor='mm')
    return out

def validate_manifest(obj):
    ensure(obj.get('date')==DATE,f'Research manifest must be for TODAY ({DATE}), not old evidence')
    ensure(str(obj.get('research_completed_at','')).startswith(DATE), 'Research must actually have been performed today')
    refs=obj.get('reference_images') or []
    observed=[r for r in refs if r.get('type')=='competitor_observed']
    ensure(len(observed)>=3,'At least three independently observed Pinterest image references must be archived today')
    ref_ids=set()
    for r in refs:
        key=r.get('id');ensure(key and key not in ref_ids,'Missing or duplicate reference ID')
        ref_ids.add(key)
        if r.get('type')=='competitor_observed':
            u=r.get('pin_url',''); parsed=urlparse(u)
            ensure(parsed.scheme=='https' and parsed.netloc in ('www.pinterest.com','pinterest.com','pin.it') and '/pin/' in parsed.path, 'Competitor needs an actual Pinterest pin URL')
            ensure(r.get('archive_status')=='saved_in_drive' and DATE in r.get('archive_file',''),'Competitor visual must be saved TODAY in the dated reference library')
            ensure(len(r.get('visual_features',''))>=20,'Competitor visual observations missing')
            ensure(r.get('metric_status')=='not_verified' or r.get('metric_status')=='verified_public','Competitor metrics may not be fabricated')
        if r.get('type')=='own_verified_winner':
            m=r.get('verified_analytics') or {}
            imp=int(m.get('impressions',0));s=int(m.get('saves',0));c=int(m.get('outbound_clicks',0))
            base=m.get('cohort_median_engagement_rate')
            rate=(s+c)/max(1,imp)
            ensure(imp>=500 and s+c>=5 and base is not None and rate>=float(base)*1.3, 'Own winner does not meet 500 impressions and cohort-relative engagement thresholds')
    concepts=obj.get('pin_concepts') or []
    ensure(len(concepts)==9,'Exactly nine researched, nonduplicate original pin concepts are required')
    ensure(len(set(x.get('destination_slug') for x in concepts))==9,'Nine distinct actual article destinations required')
    for c in concepts:
        path=c.get('destination_slug','')
        ensure(bool(re.fullmatch(r'[a-z0-9-]+\.html',path)) and (ROOT/path).is_file(),'Pin destination not a real page: '+path)
        ensure(c.get('headline') and c.get('seo_title') and c.get('description') and c.get('food_scene'),'Complete original brief required')
        ensure(c.get('research_ref_ids') and all(x in ref_ids for x in c['research_ref_ids']),'Every pin must cite archived same-day references')
        kinds={r['id']:r.get('type') for r in refs}
        ensure(any(kinds[x] in ('competitor_observed','own_verified_winner') for x in c['research_ref_ids']), 'Every pin needs a visually observed competitor or a verified own winner; brand moodboard alone is insufficient')
        ensure(c.get('layout') in ('hero','photo_first','editorial'),'Unknown layout')
        ensure(len(c.get('food_scene',''))>=30,'Food scene must be specifically described; not generic')
    return concepts

def new_photo(c,index,refmap):
    if not os.getenv('OPENAI_API_KEY'):raise PublishingBlocked('OPENAI_API_KEY GitHub repository secret is missing; first-party NEW food photographs unavailable. No recycled-photo fallback.')
    evidence='; '.join(refmap[x].get('visual_features','') for x in c['research_ref_ids'])[:450]
    prompt=(f"Original premium REALISTIC editorial food PHOTOGRAPH ONLY for an easy dinner recipe Pinterest pin; no lettering, words, logos, graphics or watermarks. "
            f"Depict this specific food/scene accurately: {c['food_scene']}. "
            f"Niche design research from observed Pinterest image references suggests: {evidence}. "
            "Use the EFFECTIVE GENERAL PRINCIPLES only: delicious physically plausible food, natural light, genuine cooking textures, intentional framing, generous high-resolution details, sophisticated food-blog photographic styling. "
            "Make it distinct from the referenced creators' exact imagery, layouts, and brand identity. Portrait 2:3 framing with centered dishes. No existing website photography reused.")
    payload=json.dumps(dict(model=OPENAI_IMAGE_MODEL,prompt=prompt,n=1,size='1024x1536',quality='medium',output_format='jpeg')).encode()
    req=urllib.request.Request('https://api.openai.com/v1/images/generations',data=payload,headers={'Content-Type':'application/json','Authorization':'Bearer '+os.environ['OPENAI_API_KEY']},method='POST')
    try:
        with urllib.request.urlopen(req, timeout=170) as resp:
            result = json.loads(resp.read())
    except urllib.error.HTTPError as exc:
        # GitHub masks the secret; expose only provider status/type/code/message.
        # In particular a 429 could mean insufficient_quota OR a rate limit.
        response = exc.read().decode('utf-8', 'replace')[:2000]
        try:
            detail = json.loads(response).get('error') or {}
            err_type = str(detail.get('type') or 'unknown')
            err_code = str(detail.get('code') or 'unknown')
            err_msg = str(detail.get('message') or '')
        except (ValueError, AttributeError):
            err_type, err_code, err_msg = 'unparsed', 'unknown', response
        secret = os.getenv('OPENAI_API_KEY') or ''
        if secret:
            err_msg = err_msg.replace(secret, '[REDACTED]')
        raise PublishingBlocked(
            f'OpenAI Images API HTTP {exc.code} | type={err_type} | '
            f'code={err_code} | {err_msg[:500]}'
        ) from None
    raw=result.get('data',[{}])[0].get('b64_json')
    if not raw:raise PublishingBlocked(f'First-party image generation gave no pixels for pin {index}')
    decoded=base64.b64decode(raw)
    with Image.open(io.BytesIO(decoded)) as image: return image.copy(),hashlib.sha256(decoded).hexdigest()

def run():
    ensure(RESEARCH.is_file(),f'Same-day research missing: {RESEARCH}. Refusing to publish uninformed designs')
    manifest=json.loads(RESEARCH.read_text(encoding='utf-8'))
    concepts=validate_manifest(manifest)
    key=os.getenv('OPENAI_API_KEY');ensure(key,'First-party image API key missing. Do not publish recycled photos.')
    ensure(RSS.is_file(),'Website Pinterest RSS feed missing')
    tree=ET.parse(RSS);channel=tree.getroot().find('channel');ensure(channel is not None,'RSS channel missing')
    if any((x.findtext('guid') or '').startswith('wfe-native-'+DATE) for x in channel.findall('item')):
        print('Already created images for today; no duplicates.');return
    DEST.mkdir(parents=True,exist_ok=True)
    refmap={r['id']:r for r in manifest['reference_images']};generated=[]
    pub_date=email.utils.format_datetime(dt.datetime.now(ZoneInfo('America/Detroit')).astimezone(dt.timezone.utc))
    for i,c in enumerate(concepts,1):
        photo,sha=new_photo(c,i,refmap)
        pin=compose(photo,c,i)
        safe=re.sub('[^a-z0-9]+','-',c['headline'].lower()).strip('-')[:55]
        filename=f'{i:02}-{safe}.jpg';out=DEST/filename
        pin.save(out,'JPEG',quality=91,optimize=True)
        generated.append({'filename':filename,'destination_slug':c['destination_slug'],'image_sha256':sha,'reference_ids':c['research_ref_ids'],'image_model':OPENAI_IMAGE_MODEL,'created_at':dt.datetime.now(dt.timezone.utc).isoformat()})
    for i,(c,g) in enumerate(zip(concepts,generated),1):
        item=ET.SubElement(channel,'item')
        ET.SubElement(item,'title').text=c['seo_title']
        ET.SubElement(item,'link').text=BASE+c['destination_slug']
        ET.SubElement(item,'guid',{'isPermaLink':'false'}).text=f'wfe-native-{DATE}-{i:02}-{g["image_sha256"][:12]}'
        ET.SubElement(item,'pubDate').text=pub_date
        ET.SubElement(item,'description').text=c['description']
        ET.SubElement(item,f'{{{MEDIA_NS}}}content',{'url':BASE+f'pinterest-daily-pins/{DATE}/{g["filename"]}','medium':'image','type':'image/jpeg'})
    for old in channel.findall('item')[:-135]:channel.remove(old)
    build=channel.find('lastBuildDate')
    if build is None:build=ET.SubElement(channel,'lastBuildDate')
    build.text=pub_date
    ET.indent(tree,space='  ');tree.write(RSS,encoding='utf-8',xml_declaration=True)
    LEDGER.parent.mkdir(parents=True,exist_ok=True)
    LEDGER.write_text(json.dumps({'date':DATE,'status':'feed_updated_not_pinterest_confirmed','research_manifest':str(RESEARCH.relative_to(ROOT)),'original_new_images':generated},indent=2))
    print(f'Published {len(generated)} newly AI-generated photo-led images to the RSS feed; Pinterest import still unverified.')

if __name__=='__main__':
    try:run()
    except PublishingBlocked as e:
        print('PUBLISHING BLOCKED:',e,file=sys.stderr)
        sys.exit(2)
