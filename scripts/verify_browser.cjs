// Run a local server on port 8765, then: node scripts/verify_browser.cjs
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.WFE_CHROMIUM ? {executablePath:process.env.WFE_CHROMIUM} : {})});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route('https://www.googletagmanager.com/**', route => route.fulfill({status:200,contentType:'text/javascript',body:'/* Analytics stub: do not record QA traffic. */'}));
  const page = await context.newPage();
  const errors=[];
  const analytics=[];
  page.on('pageerror', e=>errors.push(e.message));
  page.on('request', r=>{if(r.url().includes('googletagmanager.com/gtag/js')) analytics.push(r.url());});
  const origin='http://127.0.0.1:8765';
  await page.goto(origin+'/what-to-make-for-dinner.html');
  await page.waitForLoadState('networkidle');
  assert.equal(await page.locator('.dinner-card:visible').count(),12);
  assert.equal(analytics.length,0,'Analytics must not load before consent');
  await page.getByRole('button',{name:'No thanks',exact:true}).click();
  await page.selectOption('#filter-time','10');
  await page.selectOption('#filter-ingredient','chicken');
  assert.equal(await page.locator('.dinner-card:visible').count(),1);
  assert.equal(await page.locator('.dinner-card:visible').getAttribute('id'),'chicken-plate');
  await page.selectOption('#filter-ingredient','eggs');
  assert.equal(await page.locator('.dinner-card:visible').count(),0);
  assert.equal(await page.locator('#no-dinners').isVisible(),true);
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  assert.equal(await page.locator('.dinner-card:visible').count(),12);
  await page.selectOption('#filter-time','slow');
  assert.equal(await page.locator('.dinner-card:visible').getAttribute('id'),'salsa-chicken');
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.getByRole('button',{name:'Pick one for me',exact:true}).click();
  assert.equal(await page.locator('.dinner-card:visible').count(),1);
  await page.goto(origin+'/what-to-make-for-dinner.html?time=10&effort=minimal&ingredient=beans&utm_source=pinterest&email=private%40example.com');
  assert.equal(await page.locator('.dinner-card:visible').count(),2);
  assert.equal(analytics.length,0);
  await page.getByRole('button',{name:'Analytics choices',exact:true}).click();
  await page.getByRole('button',{name:'Allow analytics',exact:true}).click();
  await page.waitForFunction(()=>window.dataLayer?.length>=3);
  const config = await page.evaluate(()=>Array.from(window.dataLayer).map(x=>Array.from(x)).find(x=>x[0]==='config'));
  assert.equal(config[2].page_location.includes('email='),false,'Never include arbitrary query parameters');
  assert.equal(config[2].page_location.includes('utm_source=pinterest'),true);
  await page.selectOption('#filter-time','20');
  assert.equal(await page.evaluate(()=>window.dataLayer.some(x=>x[0]==='event'&&x[1]==='dinner_finder_filter')),true);
  await page.getByRole('button',{name:'Analytics choices',exact:true}).click();
  await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'No thanks',exact:true}).click()]);
  assert.equal(await page.evaluate(()=>localStorage.getItem('wfe_analytics_choice_v1')),'denied');
  assert.equal(await page.locator('script[src*="googletagmanager.com"]').count(),0);

  const shots=process.env.WFE_SCREENSHOTS || '/workspace/scratch/7ea6caf3eb0d/qa';
  fs.mkdirSync(shots,{recursive:true});
  await page.goto(origin+'/what-to-make-for-dinner.html');
  await page.screenshot({path:path.join(shots,'finder-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(shots,'finder-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile overflow');
  await page.goto(origin+'/');
  assert.equal(await page.locator('figure[data-file]').count(),14);
  assert.equal(await page.locator('figure[data-file] img').count(),14,'No duplicate images after JavaScript');
  await page.getByRole('button',{name:'Menu',exact:false}).click();
  assert.equal(await page.locator('#primary-menu').isVisible(),true);
  await page.screenshot({path:path.join(shots,'home-mobile.png'),fullPage:false});
  await page.goto(origin+'/5-ingredient-dinners.html#five-recipe-1');
  assert.equal(await page.locator('#five-recipe-1').getAttribute('open'),'');
  await page.goto(origin+'/5-47-rescue-kit.html');
  for (const href of await page.locator('a.cta').evaluateAll(items=>items.map(x=>x.href))) assert.match(href,/^https:\/\/whop\.com\//);
  await context.close();
  const noJS=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  const staticPage=await noJS.newPage();
  await staticPage.goto(origin+'/what-to-make-for-dinner.html');
  assert.equal(await staticPage.locator('.dinner-card:visible').count(),12);
  await staticPage.goto(origin+'/');
  assert.equal(await staticPage.locator('figure[data-file] img').count(),14);
  assert.equal(await staticPage.locator('a.rk[href="#"]').count(),0);
  await staticPage.goto(origin+'/5-47-rescue-kit.html');
  assert.equal(await staticPage.locator('a.cta[href="#"]').count(),0);
  await noJS.close();
  await browser.close();
  assert.deepEqual(errors,[], 'Client-side errors');
  console.log('PASS: desktop/mobile, filters, empty state, random pick, shareable filters, no-JS recipe/checkout links, analytics opt-in/withdrawal, clean measurement URLs, navigation and duplicate-image regression.');
})().catch(error=>{console.error(error);process.exit(1);});
